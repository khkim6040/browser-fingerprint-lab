/**
 * Hand-assembled WebAssembly (no toolchain): `run(n)` iterates a 32-bit LCG
 * n times and returns the state. It is the same arithmetic as the JS
 * `integer` workload, so the two timings compare JIT against wasm engine on
 * identical work.
 */
const LCG_WASM = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x06, 0x01, 0x60,
  0x01, 0x7f, 0x01, 0x7f, 0x03, 0x02, 0x01, 0x00, 0x07, 0x07, 0x01, 0x03,
  0x72, 0x75, 0x6e, 0x00, 0x00, 0x0a, 0x2d, 0x01, 0x2b, 0x01, 0x01, 0x7f,
  0x02, 0x40, 0x03, 0x40, 0x20, 0x00, 0x45, 0x0d, 0x01, 0x20, 0x01, 0x41,
  0x8d, 0xcc, 0xe5, 0x00, 0x6c, 0x41, 0xdf, 0xe6, 0xbb, 0xe3, 0x03, 0x6a,
  0x21, 0x01, 0x20, 0x00, 0x41, 0x01, 0x6b, 0x21, 0x00, 0x0c, 0x00, 0x0b,
  0x0b, 0x20, 0x01, 0x0b,
]);

export function lcgWasm(): (n: number) => number {
  const instance = new WebAssembly.Instance(new WebAssembly.Module(LCG_WASM));
  return instance.exports.run as (n: number) => number;
}
